"""Write docs/conference-coverage.md from runs/<id>/out/<id>.json (aggregate counts only, no abstract text).

Usage: python scripts/coverage_report.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

NOT_CAPTURED = [
    ("ASCO Annual / ASCO GI (meetings.asco.org)", "Terms of Use prohibit robots, scraping and text/data mining without "
     "ASCO's prior consent.", "Covered instead from the JCO supplement via Crossref (`asco-2026`, `asco-gi-2026`)."),
    ("AACR (Abstracts Online planner, Cancer Research site)", "Planner robots.txt is `Disallow: /`; journal site serves "
     "a bot challenge.", "Covered from Cancer Research supplement via Crossref (`aacr-2026`)."),
    ("WCLC (cattendee.abstractsonline.com)", "Same operator as the AACR planner; robots.txt disallows crawling.",
     "Covered from the JTO supplement via Crossref (`wclc-2026`), titles/authors only."),
    ("ASH (submit.hematology.org)", "Terms limit use to personal, non-commercial; no reuse in another service.",
     "Covered from the Blood supplement via Crossref (`ash-2025`)."),
    ("EHA (library.ehaweb.org)", "Terms: personal, non-commercial, educational use; no copying without written "
     "consent.", "Not covered: HemaSphere deposits the EHA abstract book as one record, not per-abstract DOIs. "
     "Needs a licence/export from EHA."),
    ("ESMO, ASTRO, SITC, SABCS websites", "Not contacted.", "Covered from journal supplements via Crossref."),
    ("EventScribe meetings (ctos2025, sno2023 on 2026-11-12)", "Every programme request from the pipeline's "
     "attributable User-Agent returned HTTP 403 (robots.txt itself allows access).", "Treated as a refusal: "
     "capture stopped with no data; no retry under another identity. Re-run `scripts/run_all.py ctos-2025 "
     "sno-2023` later or ask the organiser for an export. Adapter and configs are ready."),
]


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f}%" if d else "n/a"


def main() -> None:
    rows, detail = [], []
    for cfg_path in sorted((ROOT / "configs").glob("*.json")):
        cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
        cid = cfg["conference"]["id"]
        out = ROOT / "runs" / cid / "out" / f"{cid}.json"
        if not out.exists():
            rows.append(f"| {cfg['conference']['name']} | `{cid}` | `{cfg['runner']['adapter']}` | not run | | | | | |")
            continue
        doc = json.loads(out.read_text(encoding="utf-8"))
        pres = doc["presentations"]
        n = len(pres)
        authors = [a for p in pres for a in p["authors"]]
        fails = {c["id"]: c["failures"] for c in doc["qa"]["checks"] if c["failures"]}
        qa = "pass" if not fails and doc["qa"]["schemaValid"] else "fail: " + ", ".join(f"{k}={v}" for k, v in fails.items())
        rows.append(
            f"| {doc['conference']['name']} | `{cid}` | `{cfg['runner']['adapter']}` | {n:,} | "
            f"{pct(doc['coverage']['withAbstract'], n)} | {pct(sum(1 for a in authors if a.get('institution')), len(authors))} | "
            f"{pct(sum(1 for a in authors if a.get('country')), len(authors))} | {pct(doc['coverage']['tagged'], n)} | {qa} |")
        dz = Counter(x for p in pres for x in p["diseases"]).most_common(5)
        tg = Counter(x for p in pres for x in p["targets"]).most_common(5)
        dr = Counter(x for p in pres for x in p["drug"]).most_common(5)
        fmt = ", ".join(f"{k} {v:,}" for k, v in doc["coverage"]["byFormat"].items())
        detail.append(f"### {doc['conference']['name']} (`{cid}`)\n\n"
                      f"- Source: {cfg.get('source', {}).get('journal') or doc['conference']['url']}\n"
                      f"- Formats: {fmt}; sessions {len(doc['sessions']):,}; people {len(doc['people']):,}; "
                      f"sponsors {len(doc['sponsors']):,}\n"
                      f"- Top diseases: {', '.join(f'{k} ({v})' for k, v in dz) or 'none'}\n"
                      f"- Top drug targets: {', '.join(f'{k} ({v})' for k, v in tg) or 'none'}\n"
                      f"- Top drugs: {', '.join(f'{k} ({v})' for k, v in dr) or 'none'}\n")
    text = ["# Conference Coverage", "",
            "Generated by `scripts/coverage_report.py` from local runs (`runs/<id>/out/<id>.json`, git-ignored). "
            "Counts only; no abstract text is reproduced here.", "",
            "| Meeting | Config | Adapter | Abstracts | With abstract text | Author institution | Author country | Tagged | QA gate |",
            "|---|---|---|---:|---:|---:|---:|---:|---|", *rows, "",
            "Crossref-sourced meetings carry no session, date, room or presenter data (journal supplements do not "
            "include the programme), and some publishers (Elsevier: ASTRO, WCLC, ESMO; BMJ: SITC) deposit no abstract "
            "text, so those meetings are tagged from titles only.", "",
            "## Meetings not captured from their own websites", "",
            "| Source | Rule found | How it is handled |", "|---|---|---|",
            *[f"| {a} | {b} | {c} |" for a, b, c in NOT_CAPTURED], "",
            "## Per-meeting detail", "", *detail]
    (ROOT / "docs" / "conference-coverage.md").write_text("\n".join(text) + "\n", encoding="utf-8")
    print("wrote docs/conference-coverage.md")


if __name__ == "__main__":
    main()
